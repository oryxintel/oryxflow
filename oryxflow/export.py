"""
Sharing outputs between projects: ``export = True`` tasks, ``tasks_export.py``, ``FlowImport``.

The producer marks the tasks other projects may read with ``export = True``. Every
``flow.run()`` that includes one rewrites ``tasks_export.py`` at the project root (the parent
of the data dir): one external task per exported class, with its docstring, parameters and
defaults, ``persists``, the data path (relative to the export file) and ``built``, the
parameter values whose output exists. The consumer loads that file with
``FlowImport('<project dir>')`` and ``@requires`` its classes like any other dependency. An
exported task's defaults are its prod values: every exported parameter must have one, the
import binds each parameter to it (``bind()`` overrides), and downstream tasks rerun when the
producer changes a default or recomputes.

The file is rewritten from three sources: the exported tasks the run just used (their data
dir wins), the exported classes defined in project modules loaded right now, and the previous
file -- a class whose module this process never imported is carried over from it (its
``built`` re-checked on disk), so a run that imports only some task modules keeps the others'
exports. A class is dropped only when its module is loaded and no longer exports it.

A generated export imports only ``oryxflow``, which is what makes loading it from another
project safe: a module that imports its own project's files (``import cfg``) would resolve
those against the importing project instead.
"""

import ast
import copy
import datetime
import hashlib
import importlib.util
import inspect
import json
import os
import sys
import warnings
from pathlib import Path

EXPORT_FILENAME = 'tasks_export.py'
GENERATED_MARKER = '# Generated by oryxflow'

_HEADER = '''{marker} on every flow.run() -- do not edit.
"""Tasks this project exports for other projects to read (read-only: external = True).

Load them from another project and require them like your own tasks:

    exported = oryxflow.FlowImport('<path to this project>')

    @oryxflow.requires(exported.<TaskName>)
    class MyTask(oryxflow.tasks.TaskPqPandas):
        ...

Each parameter is fixed to its default (the producer's prod build); override with
exported.<TaskName>.bind(<param>=...). `built` lists the parameter values whose output
exists; 'prod': True marks the defaults.
"""
import datetime
import pathlib

import oryxflow
{extra_imports}
_HERE = pathlib.Path(__file__).resolve().parent
'''

# warnings already given this process (not-exportable classes, moved locations)
_warned = set()

# methods that decide where a task's files live: overriding one outside oryxflow means the
# export can't describe the location
_LOCATION_METHODS = ('output', '_getpath', '_resolved_dirpath')


def default_export_path():
    """``tasks_export.py`` at the project root: the parent of the data dir."""
    from oryxflow import settings
    return Path(settings.dirpath).resolve().parent / EXPORT_FILENAME


def _write_text(path, text):
    # atomic: a consumer reading mid-write must never import half a file
    path = Path(path)
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(text, encoding='utf-8')
    os.replace(str(tmp), str(path))


def _is_exported(cls):
    return bool(getattr(cls, 'export', False)) and not getattr(cls, 'external', False)


def _outputs_exist(task):
    from oryxflow.core import flatten
    outputs = flatten(task.output())
    return bool(outputs) and all(o.exists() for o in outputs)


def _str_params(task):
    return task.to_str_params(only_significant=True)


def _native(p):
    """Whether a parameter is exported as its own type (else as a plain string Parameter)."""
    from oryxflow import parameter as P
    return type(p).__module__ == 'oryxflow.parameter' and type(p) is not P.EnumParameter


def _built_values(task):
    """A ``built`` entry: the task's significant parameter values, sorted by name, as Python
    literals where they load back exactly (``built[0]['debug'] is False``), else in their
    serialized string form. Either form gives the same task_id."""
    params = dict(task.get_params())
    out = {}
    for name, text in sorted(_str_params(task).items()):
        value = getattr(task, name)
        out[name] = value if _native(params[name]) and _loads_back(repr(value), value) else text
    return out


def _from_values(cls, values):
    """``cls`` instantiated from a ``built`` entry (literal or serialized-string values; the
    ``prod`` mark is not a parameter)."""
    params = dict(cls.get_params())
    return cls(**{k: params[k].parse(v) if isinstance(v, str) else v
                  for k, v in values.items() if k in params})


def _defaults(cls):
    """The significant parameters' defaults, serialized (``_str_params`` form), or None when
    one has no default."""
    out = {}
    for name, p in cls.get_params():
        if not p.has_task_value():
            return None
        if p.significant:
            out[name] = p.serialize(p.task_value())
    return out


def _check_defaults(cls):
    for name, p in sorted(cls.get_params(), key=lambda item: item[0]):
        if not p.has_task_value():
            raise ValueError('{}.{}: exported parameters need a default -- the value consumers '
                             'should get (prod)'.format(cls.__name__, name))


def check_exported_defaults(tasks):
    """Called by ``run()`` before building: an exported task in the DAG without a default for
    every parameter stops the run, so it never publishes a build consumers can't select."""
    from oryxflow import settings, utils
    if settings.cloud_fs_enabled:
        return
    seen = set()
    for t in tasks:
        for task in utils.traverse(t):
            cls = type(task)
            if cls not in seen and _is_exported(cls):
                seen.add(cls)
                _check_defaults(cls)


def _entry(task, defaults):
    """A ``built`` entry, marked ``'prod': True`` when its values are the defaults."""
    values = _built_values(task)
    if defaults is not None and _str_params(task) == defaults:
        values['prod'] = True
    return values


def _env_of(path, dirpath):
    """Whether ``path`` is an ``env=`` folder of ``dirpath`` (a ``Workflow(env=...)`` run)."""
    p = Path(path).resolve()
    return p.name.startswith('env=') and _same_dir(p.parent, dirpath)


def _key(values):
    return json.dumps(values, sort_keys=True)


def _module_name(path):
    return 'oryxflow_import_{}'.format(
        hashlib.md5(str(Path(path).resolve()).encode('utf-8')).hexdigest()[:12])


def _exec_export(path, register=False):
    """Execute an export file in isolation; returns the module."""
    path = Path(path).resolve()
    name = _module_name(path)
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    if register:
        sys.modules[name] = mod      # inspect / pickling look classes up here
    try:
        spec.loader.exec_module(mod)
    except BaseException:
        if register:
            sys.modules.pop(name, None)
        raise
    return mod


def _export_classes(mod):
    from oryxflow.tasks import TaskData
    return {k: v for k, v in vars(mod).items()
            if inspect.isclass(v) and issubclass(v, TaskData) and v.__module__ == mod.__name__}


def _previous_classes(path):
    """The classes of the previous export file, or {} when there is none or it won't load."""
    if not Path(path).is_file():
        return {}
    try:
        return _export_classes(_exec_export(path))
    except Exception as e:
        warnings.warn('oryxflow: the existing {} does not load ({}: {}); exports it held for '
                      'modules this run did not import are dropped'.format(
                          path, type(e).__name__, e), UserWarning)
        return {}


def _source_of(cls, root):
    """The class's module file relative to the project root (posix), or None."""
    f = getattr(sys.modules.get(cls.__module__), '__file__', None)
    if not f:
        return None
    try:
        return Path(f).resolve().relative_to(Path(root).resolve()).as_posix()
    except ValueError:
        return None


def _loaded_project_files(root):
    root = Path(root).resolve()
    out = set()
    for mod in list(sys.modules.values()):
        f = getattr(mod, '__file__', None)
        if not f:
            continue
        try:
            out.add(Path(f).resolve().relative_to(root).as_posix())
        except (ValueError, OSError):
            continue
    return out


def _project_classes(root):
    """(exported classes, names of all task classes) defined in modules under the project root
    that are loaded right now."""
    from oryxflow.tasks import TaskData
    root = Path(root).resolve()
    exported, names, stack = [], set(), list(TaskData.__subclasses__())
    while stack:
        cls = stack.pop()
        stack.extend(cls.__subclasses__())
        if cls.__module__.startswith('oryxflow_import_'):
            continue     # another project's export loaded with FlowImport, not this project's
        mod = sys.modules.get(cls.__module__)
        f = getattr(mod, '__file__', None)
        if not f or getattr(mod, cls.__name__, None) is not cls:
            continue     # gone from its module (redefined) or not a module-level class
        try:
            Path(f).resolve().relative_to(root)
        except ValueError:
            continue
        names.add(cls.__name__)
        if _is_exported(cls):
            exported.append(cls)
    return exported, names


def _base_class(cls):
    return next(c for c in cls.__mro__[1:] if c.__module__.startswith('oryxflow.tasks'))


def _not_exportable(cls):
    """Why ``cls`` can't be described in an export, or None."""
    for name in _LOCATION_METHODS:
        owner = next((c for c in cls.__mro__ if name in c.__dict__), None)
        if owner is not None and not (owner.__module__ == 'oryxflow'
                                      or owner.__module__.startswith('oryxflow.')):
            return 'it overrides {}(), so its file location cannot be exported'.format(name)
    target = getattr(cls, 'target_class', None)
    if target is not None and not target.__module__.startswith('oryxflow.targets'):
        return 'its target_class {} is not an oryxflow target'.format(target.__name__)
    if getattr(cls, 'keep_versions', False) and getattr(cls, 'code_version', None) is not None:
        return 'keep_versions puts outputs under a code-version folder another project cannot locate'
    return None


def _loads_back(src, value):
    try:
        return eval(src, {'datetime': datetime}) == value
    except Exception:
        return False


def _param_source(name, p):
    from oryxflow import parameter as P
    kind = type(p)
    native = kind.__module__ == 'oryxflow.parameter' and kind is not P.EnumParameter
    default = None
    if p.has_task_value():
        default = p._default
        if not (native and _loads_back(repr(default), default)):
            # enums, custom parameter types and defaults with no literal form (a Path, a
            # numpy scalar) are exported as plain strings in their serialized form, which
            # gives the same task_id
            native = False
            default = p.serialize(p.task_value())
    args = []
    if native and isinstance(p, P.ChoiceParameter):
        args.append('choices={!r}'.format(p._choices))
    if p.has_task_value():
        args.append('default={!r}'.format(default))
    if not p.significant:
        args.append('significant=False')
    return '{} = oryxflow.parameter.{}({})'.format(
        name, kind.__name__ if native else 'Parameter', ', '.join(args))


def _path_source(dirpath, export_dir):
    dirpath = Path(dirpath).resolve()
    try:
        rel = os.path.relpath(str(dirpath), str(Path(export_dir).resolve()))
    except ValueError:          # another drive: no relative form
        return 'path = {!r}'.format(dirpath.as_posix())
    return 'path = str(_HERE / {!r})'.format(Path(rel).as_posix())


def _docstring(cls):
    doc = cls.__dict__.get('__doc__')
    if not doc or not doc.strip():
        return None
    doc = inspect.cleandoc(doc).replace('\\', '\\\\').replace('"""', '\\"\\"\\"')
    lines = doc.splitlines()
    if len(lines) == 1:
        return '    """{}"""'.format(lines[0])
    body = '\n'.join(('    ' + ln) if ln else '' for ln in lines[1:])
    return '    """{}\n{}\n    """'.format(lines[0], body)


def _class_source(cls, dirpath, built, export_dir, source=None):
    from oryxflow import settings
    base = _base_class(cls)
    lines = ['class {}({}.{}):'.format(cls.__name__, base.__module__, base.__name__)]
    doc = _docstring(cls)
    if doc:
        lines.append(doc)
    lines.append('    external = True')
    if source:
        lines.append('    export_source = {!r}'.format(source))
    persist = getattr(cls, 'persists', None) or getattr(cls, 'persist', ['data'])
    lines.append('    persists = {!r}'.format(list(persist)))
    lines.append('    ' + _path_source(dirpath, export_dir))
    if getattr(cls, 'target_ext', None) != getattr(base, 'target_ext', None):
        lines.append('    target_ext = {!r}'.format(cls.target_ext))
    target = getattr(cls, 'target_class', None)
    if target is not None and target is not getattr(base, 'target_class', None):
        lines.append('    target_class = {}.{}'.format(target.__module__, target.__name__))
    if hasattr(cls, 'task_group'):
        lines.append('    task_group = {!r}'.format(getattr(cls, 'task_group')))
    if getattr(cls, 'target_dir', None) is not None:
        lines.append('    target_dir = {!r}'.format(cls.target_dir))
    if not (settings.save_with_param and getattr(cls, 'save_attrib', True)):
        lines.append('    save_attrib = False')
    # by name: get_params() follows Parameter creation order, which for copied (@requires)
    # parameters is module import order -- so it differed by entry point and churned the file
    for name, p in sorted(cls.get_params(), key=lambda item: item[0]):
        lines.append('    ' + _param_source(name, p))
    if len(built) <= 1:
        lines.append('    built = {!r}'.format(built))
    else:      # one value set per line: a new build is a one-line diff
        lines.append('    built = [')
        lines.extend('        {!r},'.format(b) for b in built)
        lines.append('    ]')
    return '\n'.join(lines)


def _same_dir(a, b):
    try:
        return Path(a).resolve() == Path(b).resolve()
    except Exception:
        return False


def _still_built(old, values_list, dirpath):
    """Instances of the previous file's built values that still have output, checked with its
    own class (which knows where those files are) -- only when that is the directory being
    written."""
    if old is None or not _same_dir(getattr(old, 'path', None) or '', dirpath):
        return []
    out = []
    for values in values_list:
        try:
            task = _from_values(old, values)
            if _outputs_exist(task):
                out.append(task)
        except Exception:
            continue      # parameters changed since: that value set is gone
    return out


def _marks_export(node):
    return isinstance(node, ast.ClassDef) and any(
        isinstance(s, ast.Assign) and len(s.targets) == 1 and isinstance(s.targets[0], ast.Name)
        and s.targets[0].id == 'export' and isinstance(s.value, ast.Constant)
        and s.value.value is True for s in node.body)


def _unloaded_exports(root, loaded, listed):
    """``{module file: [class names]}``: classes marked ``export = True`` in project modules
    this process never imported (top level and one folder down) that the file doesn't list."""
    root = Path(root)
    out = {}
    for f in sorted(list(root.glob('*.py')) + list(root.glob('*/*.py'))):
        rel = f.relative_to(root).as_posix()
        if rel in loaded or f.name == EXPORT_FILENAME or rel.startswith('.'):
            continue
        try:
            text = f.read_text(encoding='utf-8')
            if 'export' not in text:
                continue
            tree = ast.parse(text)
        except (OSError, SyntaxError, ValueError, UnicodeDecodeError):
            continue
        names = [n.name for n in tree.body if _marks_export(n) and n.name not in listed]
        if names:
            out[rel] = names
    return out


class FlowExport:
    """
    Write ``tasks_export.py``: the tasks this project exports (``export = True``) as read-only
    external tasks another project loads with :class:`FlowImport`.

    ``flow.run()`` calls this for you whenever the flow includes an exported task, so you
    rarely need it directly.

    Args:
        tasks (obj, list): task instances just run; their exported ones with output on disk
            are added to ``built``
        flows (obj, list): flows whose tasks (and everything upstream) count as just run
        save (bool): write the file (only when its content changed); otherwise only return it
        path_export (str): where to write; default ``tasks_export.py`` next to the data dir

    Returns (``generate()``): the file's source code.

    Attributes:
        unloaded (dict): after ``generate()``, ``{module file: [class names]}`` of classes
            marked ``export = True`` in project modules this process never imported, which
            the file therefore doesn't list yet
    """

    def __init__(self, tasks=None, flows=None, save=False, path_export=None):
        import oryxflow
        self.unloaded = {}
        self._roots = None       # the run's own tasks (auto_export): for the experiment guard
        tasks = [] if tasks is None else tasks
        tasks = list(tasks) if isinstance(tasks, (list, tuple)) else [tasks]
        flows = [] if flows is None else flows
        flows = list(flows) if isinstance(flows, (list, tuple)) else [flows]
        for flow in flows:
            tasks.extend(oryxflow.taskflow_upstream(flow.get_task()))
        self.tasks = tasks
        self.save = save
        self.path_export = Path(path_export) if path_export is not None else default_export_path()

    def _collect(self):
        """``({class name: cls}, names of loaded project task classes)``."""
        chosen = {}

        def add(cls):
            prev = chosen.get(cls.__name__)
            if prev is not None and prev is not cls:
                if (prev.__module__, prev.__qualname__) != (cls.__module__, cls.__qualname__):
                    raise ValueError(
                        'two exported tasks are named {}: {}.{} and {}.{} -- task names must be '
                        'unique within a project (they name the output files)'.format(
                            cls.__name__, prev.__module__, prev.__qualname__,
                            cls.__module__, cls.__qualname__))
            chosen[cls.__name__] = cls   # a redefinition (same module + name): latest wins

        exported, names = _project_classes(self.path_export.parent)
        for cls in exported:
            add(cls)
        for t in self.tasks:
            if _is_exported(type(t)):
                add(type(t))
                names.add(type(t).__name__)
        return chosen, names

    def generate(self):
        from oryxflow import settings
        chosen, loaded = self._collect()
        previous = _previous_classes(self.path_export)
        export_dir = self.path_export.parent
        entries, extra = {}, set()

        for name, cls in chosen.items():
            why = _not_exportable(cls)
            if why:
                if cls not in _warned:
                    _warned.add(cls)
                    warnings.warn('{}: not exported -- {}'.format(name, why), UserWarning)
                continue
            if {'built', 'export_source', 'bind', 'prod'} & set(dict(cls.get_params())):
                raise ValueError("{}: parameters named 'built', 'export_source', 'bind' or 'prod' "
                                 "clash with the export's own attributes -- rename them".format(name))
            _check_defaults(cls)
            defaults = _defaults(cls)
            if getattr(cls, 'target_ext', None) in ('pkl', 'pickle'):
                warnings.warn('{}: exported as a pickle, which another project may not be able to '
                              'load without this project\'s code -- prefer parquet, csv or json for '
                              'exported tasks'.format(name), UserWarning)
            old = previous.get(name)
            ran = [t for t in self.tasks if type(t) is cls]
            # where consumers read: a class-level path is the code's own decision; otherwise
            # the published location stays put (a scratch env= run must not re-point
            # consumers); the first run decides it
            if getattr(cls, 'path', None) is not None:
                dirpath = getattr(cls, 'path')
            elif old is not None:
                dirpath = old.path
            elif ran:
                dirpath = ran[0]._resolved_dirpath()
            else:
                dirpath = settings.dirpath
            # an env= run (Workflow(..., env='dev')) is an experiment beside the published
            # folder: kept out of built, and not a move
            moved = [t for t in ran if not _same_dir(t._resolved_dirpath(), dirpath)
                     and not _env_of(t._resolved_dirpath(), dirpath)]
            if moved and (name, str(moved[0]._resolved_dirpath())) not in _warned:
                _warned.add((name, str(moved[0]._resolved_dirpath())))
                warnings.warn(
                    '{}: this run wrote to {}, but {} keeps pointing consumers at {}. To publish '
                    'the new location, delete the {} class from {} and run again.'.format(
                        name, moved[0]._resolved_dirpath(), EXPORT_FILENAME, Path(dirpath),
                        name, EXPORT_FILENAME), UserWarning)
            published = [t for t in ran
                         if _same_dir(t._resolved_dirpath(), dirpath) and _outputs_exist(t)]
            self._guard(name, published, defaults)
            built = {_key(_str_params(t)): _entry(t, defaults) for t in published}
            for t in _still_built(old, getattr(old, 'built', []), dirpath):
                built.setdefault(_key(_str_params(t)), _entry(t, defaults))
            entries[name] = (cls, dirpath, [built[k] for k in sorted(built)],
                             _source_of(cls, export_dir))

        files = _loaded_project_files(export_dir)
        for name, old in previous.items():
            if name in entries:
                continue
            source = getattr(old, 'export_source', None)
            if source is not None:
                if source in files or not (export_dir / source).is_file():
                    continue  # its module is loaded and no longer exports it, or is gone
            elif name in loaded:
                continue      # no recorded module: a loaded class of that name doesn't export
            defaults = _defaults(old)
            built = {_key(_str_params(t)): _entry(t, defaults)
                     for t in _still_built(old, getattr(old, 'built', []), old.path)}
            entries[name] = (old, old.path, [built[k] for k in sorted(built)], source)
        self.unloaded = _unloaded_exports(export_dir, files, set(entries))

        blocks = []
        for name in sorted(entries):
            cls, dirpath, built, source = entries[name]
            for mod in {_base_class(cls).__module__, getattr(getattr(cls, 'target_class', None), '__module__', None)}:
                if mod and mod not in ('oryxflow.tasks', 'oryxflow.targets'):
                    extra.add('import {}'.format(mod))
            blocks.append(_class_source(cls, dirpath, built, export_dir, source))
        source = _HEADER.format(marker=GENERATED_MARKER,
                                extra_imports=''.join(i + '\n' for i in sorted(extra)))
        source += ''.join('\n\n' + b + '\n' for b in blocks)
        try:
            exec(compile(source, str(self.path_export), 'exec'),
                 {'__file__': str(self.path_export), '__name__': 'oryxflow_export_check'})
        except Exception as e:
            raise ValueError('the generated {} would not load ({}: {}); not written'.format(
                EXPORT_FILENAME, type(e).__name__, e))
        if self.save:
            try:
                current = self.path_export.read_text(encoding='utf-8')
            except OSError:
                current = None
            if current != source:
                _write_text(self.path_export, source)
        return source

    def _guard(self, name, published, defaults):
        """Warn when the run wrote a non-default build of an exported task into the published
        folder because the run itself was asked for those values (an experiment), not because
        a task in the producer needs that build (an aggregator over every sector)."""
        if not self._roots or defaults is None:
            return
        asked = {}
        for root in self._roots:
            own = _defaults(type(root)) or {}
            for k, v in _str_params(root).items():
                if k in own and v != own[k]:
                    asked[k] = v
        for t in published:
            names = sorted(k for k, v in _str_params(t).items()
                           if v != defaults.get(k) and asked.get(k) == v)
            key = ('experiment', name, tuple(names))
            if names and key not in _warned:
                _warned.add(key)
                warnings.warn(
                    "{}: experiment written to the prod data folder (non-default {}); run "
                    "experiments with Workflow(..., env='dev')".format(
                        name, ', '.join('{}={}'.format(k, _str_params(t)[k]) for k in names)),
                    UserWarning)


def auto_export(tasks):
    """Called by ``run()``: rewrite ``tasks_export.py`` when the run included an exported task.
    Never fails the run: returns the problems (``run()`` puts them in ``RunResult.warnings``,
    the log and the event stream) and warns."""
    from oryxflow import settings, utils
    if settings.cloud_fs_enabled:
        return []
    try:
        dag = []
        for t in tasks:
            dag.extend(utils.traverse(t))
        if not any(_is_exported(type(t)) for t in dag):
            # a task that just stopped exporting must still leave the file
            path = default_export_path()
            try:
                text = path.read_text(encoding='utf-8')
            except OSError:
                return []
            if not any('\nclass {}('.format(type(t).__name__) in text for t in dag
                       if not getattr(t, 'external', False)):
                return []
        export = FlowExport(tasks=dag, save=True)
        export._roots = tasks
        export.generate()
        for module, names in export.unloaded.items():
            if ('unloaded', module) not in _warned:
                _warned.add(('unloaded', module))
                warnings.warn(
                    '{}: {} marked export = True, but this run did not import {}, so {} does not '
                    'list {} yet -- run an entry point that imports it once'.format(
                        module, ', '.join(names), module, EXPORT_FILENAME,
                        'it' if len(names) == 1 else 'them'), UserWarning)
        return []
    except Exception as e:
        msg = ('oryxflow: could not update {} -- consumers still read the previous one: '
               '{}: {}').format(EXPORT_FILENAME, type(e).__name__, e)
        warnings.warn(msg, UserWarning)
        return [msg]


def bind(cls, **values):
    """``cls`` with some parameters set to other values than its exported defaults:
    ``@requires(exported.X.bind(refresh='2026-07-18'))`` (compare with last quarter).

    Every parameter of an imported task is already fixed to the producer's default (its prod
    build); ``bind()`` overrides the ones you name. None is copied onto the task that requires
    it, so they don't enter that task's parameters or any downstream task_id, and your task
    reruns when a value changes. A ``built`` entry works as is: ``X.bind(**X.built[0])``."""
    params = dict(cls.get_params())
    values = {k: v for k, v in values.items() if not (k == 'prod' and k not in params)}
    unknown = sorted(set(values) - set(params))
    if unknown:
        raise TypeError('{}.bind(): no parameter {} -- it has: {}'.format(
            cls.__name__, ', '.join(unknown), ', '.join(sorted(params)) or 'none'))
    attrs = {'__module__': cls.__module__, '__doc__': cls.__doc__,
             '_oryxflow_bound': frozenset(getattr(cls, '_oryxflow_bound', ())) | set(values)}
    for name, value in values.items():
        p = copy.copy(params[name])      # keeps its declaration order
        p._default = p.parse(value) if isinstance(value, str) else value
        p.task_value()                   # validates now, not at a far-away instantiation
        attrs[name] = p
    return type(cls)(cls.__name__, (cls,), attrs)


class FlowImport:
    """
    Load another project's exported tasks (its ``tasks_export.py``, written by its
    ``flow.run()``) and use them like your own::

        exported = oryxflow.FlowImport('../project1')

        @oryxflow.requires(exported.SectorReturns)
        class MyTask(oryxflow.tasks.TaskPqPandas):
            ...

    Every parameter of an imported task is fixed to its exported default, which is the other
    project's prod build: nothing is copied onto ``MyTask``, so its parameters and task_id
    don't change, and it reruns when the other project changes a default (a new quarter) or
    recomputes that build. The files are read where the other project keeps them. The
    imported tasks are ``external``: they never run from here; a missing output stops the
    run and names what is built.

    Other values: ``exported.SectorReturns.bind(sector='retail')`` where you require it (see
    :func:`bind`), or an instance in your own ``requires()`` for a value that varies with your
    task, ``exported.SectorReturns(sector=self.sector)``.

    Args:
        path (str): the other project's folder, or the export file itself
        module (str): file name in that folder (default ``tasks_export``)

    Attributes:
        tasks (dict): ``{name: task class}``; each is also an attribute (``exported.Name``)
        path (Path): the export file loaded
    """

    def __init__(self, path, module='tasks_export'):
        p = Path(path)
        if p.suffix != '.py':
            p = p / (module if str(module).endswith('.py') else '{}.py'.format(module))
        if not p.is_file():
            raise FileNotFoundError(
                "FlowImport: {} not found -- the other project writes it when its flow.run() "
                "includes a task with export = True".format(p))
        text = p.read_text(encoding='utf-8')
        if not text.startswith(GENERATED_MARKER):
            warnings.warn(
                '{} was not generated by oryxflow: its own imports resolve against this '
                'project, not its folder'.format(p), UserWarning, stacklevel=2)
        mod = _exec_export(p, register=True)
        self.path = p
        self.module_obj = mod
        self.tasks = _export_classes(mod)
        for cls in self.tasks.values():
            params = dict(cls.get_params())
            # the exported defaults are prod: no parameter passes through from a consumer
            cls._oryxflow_bound = frozenset(params)
            if 'bind' not in params:         # never shadow a producer parameter (old files)
                cls.bind = classmethod(bind)

    def __getattr__(self, name):
        tasks = self.__dict__.get('tasks')
        if tasks is not None and name in tasks:
            return tasks[name]
        raise AttributeError('{} exports no task {!r}; it exports: {}'.format(
            self.__dict__.get('path'), name, ', '.join(sorted(tasks or {})) or 'nothing'))

    def __dir__(self):
        return sorted(set(super().__dir__()) | set(self.__dict__.get('tasks') or {}))
